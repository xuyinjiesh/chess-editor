function randomSkillOptions(count = 3, exclude = []) {
    const excluded = new Set(exclude);
    const pool = IncidentSkillKinds.filter((k) => !excluded.has(k));
    const out = [];
    while (out.length < count && pool.length > 0) {
        const idx = Math.floor(Math.random() * pool.length);
        out.push(pool[idx]);
        pool.splice(idx, 1);
    }
    return out;
}
